"""Turns the text on the tag artwork into vector outlines, so print files never depend on a font.

Run it only when the wording or the type settings change; it needs the dev tools (fonttools, brotli):

    uv run python scripts/outline_tag_text.py

It writes cartag/qr/tag_text.py and the same paths for the website in web/src/components/tagText.ts.
That is plain path data on a 100 x 100 tag, so neither the app nor the site needs a font library.
"""

from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2"
OUT = ROOT / "cartag/qr/tag_text.py"
WEB_OUT = ROOT / "web/src/components/tagText.ts"

# The artwork on a 100 x 100 tag, y pointing down. Positions are measured from the approved designs.
CENTRE_X = 50.0
# Axes are (weight, width): CAR is the widest, heaviest cut; TAG is light at normal width.
LOGO = {"baseline": 25.8, "cap": 8.7, "width": 64.0, "car": (900, 125), "tag": (330, 100)}
LINES = {
    "contact": {"text": "CONTACT THE OWNER", "baseline": 79.6, "cap": 3.0, "width": 64.0, "axes": (500, 100)},
    "scan": {"text": "SCAN.", "baseline": 89.0, "cap": 4.3, "width": 21.0, "axes": (800, 100)},
}


class SvgPen(BasePen):
    """Collects absolute M, L, C, Z commands. Quadratic curves arrive here already converted to cubic."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.parts: list[str] = []

    @staticmethod
    def _n(value: float) -> str:
        return f"{value:.3f}".rstrip("0").rstrip(".")

    def _pt(self, p) -> str:
        return f"{self._n(p[0])} {self._n(p[1])}"

    def _moveTo(self, p):
        self.parts.append(f"M{self._pt(p)}")

    def _lineTo(self, p):
        self.parts.append(f"L{self._pt(p)}")

    def _curveToOne(self, p1, p2, p3):
        self.parts.append(f"C{self._pt(p1)} {self._pt(p2)} {self._pt(p3)}")

    def _closePath(self):
        self.parts.append("Z")


def instance(wght: int, wdth: int) -> TTFont:
    return instantiateVariableFont(TTFont(FONT), {"wght": wght, "wdth": wdth}, inplace=False)


def run_width(font: TTFont, text: str, tracking: float) -> float:
    """Width in font units: advances plus tracking between letters (none after the last one)."""
    cmap = font.getBestCmap()
    advances = [font["hmtx"][cmap[ord(c)]][0] for c in text]
    return sum(advances) + tracking * (len(text) - 1)


def draw(
    font: TTFont, text: str, x: float, baseline: float, size_per_unit: float, tracking: float
) -> tuple[str, float]:
    """Draws the text starting at x. Returns the path and the x where it ended."""
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    pen = SvgPen(glyphs)
    cursor = x
    for char in text:
        name = cmap[ord(char)]
        # y is flipped: font units grow upwards, the tag grows downwards.
        tpen = TransformPen(pen, (size_per_unit, 0, 0, -size_per_unit, cursor, baseline))
        glyphs[name].draw(tpen)
        cursor += (font["hmtx"][name][0] + tracking) * size_per_unit
    return "".join(pen.parts), cursor - tracking * size_per_unit


def line(spec: dict) -> str:
    font = instance(*spec["axes"])
    cap_units = font["OS/2"].sCapHeight
    k = spec["cap"] / cap_units
    plain = run_width(font, spec["text"], 0) * k
    tracking = (spec["width"] - plain) / (len(spec["text"]) - 1) / k
    start = CENTRE_X - spec["width"] / 2
    path, _ = draw(font, spec["text"], start, spec["baseline"], k, tracking)
    return path


def logo() -> tuple[str, str]:
    car_font = instance(*LOGO["car"])
    tag_font = instance(*LOGO["tag"])
    k = LOGO["cap"] / car_font["OS/2"].sCapHeight
    width = (run_width(car_font, "CAR", 0) + run_width(tag_font, "TAG", 0)) * k
    # A small natural width mismatch is absorbed by tracking, so the mark fills exactly the measured width.
    tracking = (LOGO["width"] - width) / 5 / k
    start = CENTRE_X - LOGO["width"] / 2
    car, end = draw(car_font, "CAR", start, LOGO["baseline"], k, tracking)
    tag, _ = draw(tag_font, "TAG", end + tracking * k, LOGO["baseline"], k, tracking)
    print(f"logo natural width {width:.1f} (target {LOGO['width']}), tracking {tracking:.1f} units")
    return car, tag


def main() -> None:
    car, tag = logo()
    body = [
        '"""Outlines of the text on the tag artwork, on a 100 x 100 tag. Generated by scripts/outline_tag_text.py."""',
        "",
        f'LOGO_CAR = "{car}"',
        f'LOGO_TAG = "{tag}"',
    ]
    for name, spec in LINES.items():
        body.append(f'{name.upper()} = "{line(spec)}"')
    OUT.write_text("\n".join(body) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    # The website draws the same tag, so it gets the same outlines.
    web = ["/** Outlines of the text on the tag artwork, on a 100 x 100 tag. Generated by scripts/outline_tag_text.py. */"]  # noqa: E501
    for line_text in body[2:]:
        name, value = line_text.split(" = ", 1)
        web.append(f"export const {name} = {value};")
    WEB_OUT.write_text("\n".join(web) + "\n", encoding="utf-8")
    print(f"wrote {WEB_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
